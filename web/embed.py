#!/usr/bin/env python3
"""Gzip a file and emit it as a C array: embed.py <input> <output.c> <symbol>"""
import gzip
import sys

src, dst, symbol = sys.argv[1:4]
data = gzip.compress(open(src, "rb").read(), 9, mtime=0)
with open(dst, "w") as out:
    out.write("// Generated by web/embed.py - do not edit.\n")
    out.write(f"const unsigned char {symbol}[] = {{\n")
    for i in range(0, len(data), 16):
        out.write("    " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
    out.write("};\n")
    out.write(f"const unsigned int {symbol}_len = {len(data)};\n")
